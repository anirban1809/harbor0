import {chromium} from 'playwright';
const browser=await chromium.launch({headless:true,channel:'chrome'});
const page=await browser.newPage({viewport:{width:780,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('file:///Users/anirban/Documents/Code/files/outputs/01a0ed96-b4bf-7712-aa87-668ffc522cd3/income-preview.html');
const frame=page.frameLocator('iframe');
await frame.locator('#h-revenue').waitFor();
await page.waitForTimeout(600);
if(await frame.locator('#h-revenue').textContent()!=='$140')throw new Error('Wrong revenue');
if(await frame.locator('#h-draw').textContent()!=='$0')throw new Error('Wrong draw');
await frame.locator('#h-pricing').selectOption('1');
if(await frame.locator('#h-revenue').textContent()!=='$120')throw new Error('Pricing switch failed');
await frame.locator('#h-pricing').selectOption('2');
await frame.locator('#h-paid').fill('10');await frame.locator('#h-accounts').fill('10000');
await frame.locator('#h-use').fill('60');
if(await frame.locator('#h-needed').textContent()!=='Not viable')throw new Error('Loss detection failed');
await frame.locator('#h-paid').fill('20');await frame.locator('#h-use').fill('30');await frame.locator('#h-rate').fill('6.95');
if(await frame.locator('#h-needed').textContent()!=='3,018')throw new Error('Viable cost scenario failed');
await frame.locator('#h-paid').fill('2');await frame.locator('#h-use').fill('80');await frame.locator('#h-rate').fill('15');await frame.locator('#h-accounts').fill('1000');
await page.screenshot({path:'/Users/anirban/Documents/Code/files/outputs/01a0ed96-b4bf-7712-aa87-668ffc522cd3/income-desktop.png',fullPage:true});
await page.setViewportSize({width:360,height:1300});await page.waitForTimeout(300);
await page.screenshot({path:'/Users/anirban/Documents/Code/files/outputs/01a0ed96-b4bf-7712-aa87-668ffc522cd3/income-mobile.png',fullPage:true});
const inner=page.frames().find(f=>f!==page.mainFrame());
const dimensions=await inner.evaluate(()=>({width:document.documentElement.clientWidth,scrollWidth:document.documentElement.scrollWidth}));
if(dimensions.scrollWidth>dimensions.width)throw new Error('Mobile overflow '+JSON.stringify(dimensions));
if(errors.length)throw new Error(errors.join('\n'));
console.log('Verified default, edited, loss and mobile states.');
await browser.close();
