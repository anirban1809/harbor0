import sharp from 'sharp';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, URL } from 'node:url';
import { Buffer } from 'node:buffer';
import console from 'node:console';

const root = fileURLToPath(new URL('../', import.meta.url));
const source = path.join(root, 'assets/branding/logo.svg');
async function save(file, content) {
  const destination = path.join(root, file);
  await mkdir(path.dirname(destination), { recursive: true });
  await writeFile(destination, content);
}
async function png(size) {
  return sharp(source).resize(size, size).png().toBuffer();
}
// Desktop docks and taskbars show icons unmasked, so the mark sits on its own tile,
// sized to the macOS icon grid (824px rounded square on a 1024px canvas).
async function tiled(size) {
  const scale = size / 1024;
  const tile = Math.round(824 * scale);
  const offset = Math.round(100 * scale);
  const radius = Math.round(185 * scale);
  const mark = Math.round(tile * 0.74);
  const background = Buffer.from(
    `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}">
      <defs>
        <filter id="shadow" x="-20%" y="-20%" width="140%" height="140%">
          <feDropShadow dx="0" dy="${10 * scale}" stdDeviation="${12 * scale}" flood-color="#000" flood-opacity="0.28"/>
        </filter>
      </defs>
      <rect x="${offset}" y="${offset}" width="${tile}" height="${tile}" rx="${radius}" fill="#ffffff" filter="url(#shadow)"/>
    </svg>`,
  );
  return sharp(background)
    .composite([{ input: await png(mark), gravity: 'center' }])
    .png()
    .toBuffer();
}

// Preserve the transparent master on every surface that supports alpha.
await save('apps/desktop/assets/icon.png', await tiled(1024));
await save('apps/web/app/icon.png', await png(512));
await save('apps/web/app/apple-icon.png', await png(180));
// An inline image also works in Electron's file:// renderer, without URL routing.
const inlineIcon = (await png(128)).toString('base64');
await save(
  'apps/web/lib/brand-icon.ts',
  `// Generated by scripts/generate-app-icons.mjs from assets/branding/logo.svg.\nexport const brandIconSrc =\n  'data:image/png;base64,${inlineIcon}';\n`,
);

// ICO entries use PNG payloads at each browser/Windows icon size.
const sizes = [16, 32, 48, 64, 128, 256];
const images = await Promise.all(
  sizes.map(async (size) =>
    sharp(await png(size))
      .ensureAlpha()
      .png()
      .toBuffer(),
  ),
);
const header = Buffer.alloc(6 + sizes.length * 16);
header.writeUInt16LE(1, 2);
header.writeUInt16LE(sizes.length, 4);
let offset = header.length;
images.forEach((buffer, index) => {
  const entry = 6 + index * 16;
  header[entry] = header[entry + 1] = sizes[index] % 256;
  header.writeUInt16LE(1, entry + 4);
  header.writeUInt16LE(32, entry + 6);
  header.writeUInt32LE(buffer.length, entry + 8);
  header.writeUInt32LE(offset, entry + 12);
  offset += buffer.length;
});
await save('apps/web/app/favicon.ico', Buffer.concat([header, ...images]));

// macOS template icons require a monochrome alpha mask for light/dark menu bars.
const { data, info } = await sharp(source)
  .ensureAlpha()
  .raw()
  .toBuffer({ resolveWithObject: true });
const mask = Buffer.alloc(info.width * info.height * 4);
let left = info.width,
  top = info.height,
  right = 0,
  bottom = 0;
for (let y = 0; y < info.height; y++) {
  for (let x = 0; x < info.width; x++) {
    const pixel = y * info.width + x;
    const alpha = data[pixel * info.channels + 3];
    mask[pixel * 4 + 3] = alpha;
    if (alpha > 128) {
      left = Math.min(left, x);
      top = Math.min(top, y);
      right = Math.max(right, x);
      bottom = Math.max(bottom, y);
    }
  }
}
for (const [file, size] of [
  ['trayTemplate.png', 18],
  ['trayTemplate@2x.png', 36],
]) {
  const output = await sharp(mask, { raw: { width: info.width, height: info.height, channels: 4 } })
    .extract({ left, top, width: right - left + 1, height: bottom - top + 1 })
    .resize(size, size, { fit: 'contain', background: '#00000000' })
    .png()
    .toBuffer();
  await save(`apps/desktop/assets/${file}`, output);
}
console.log('Updated web and desktop icons from assets/branding/logo.svg.');
